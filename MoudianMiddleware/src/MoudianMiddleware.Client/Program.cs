using Microsoft.AspNetCore.Components.Authorization;
using Microsoft.AspNetCore.Components.Web;
using Microsoft.AspNetCore.Components.WebAssembly.Hosting;
using MoudianMiddleware.Client;
using MoudianMiddleware.Client.Services;
using MoudianMiddleware.Client.ViewModels;

var builder = WebAssemblyHostBuilder.CreateDefault(args);
builder.RootComponents.Add<App>("#app");
builder.RootComponents.Add<HeadOutlet>("head::after");
var apiBase = new Uri(builder.HostEnvironment.BaseAddress, "api/");
builder.Services.AddAuthorizationCore();
builder.Services.AddScoped<TokenStore>();
builder.Services.AddScoped<ClientAuthenticationStateProvider>();
builder.Services.AddScoped<AuthenticationStateProvider>(sp => sp.GetRequiredService<ClientAuthenticationStateProvider>());
builder.Services.AddScoped<AuthSessionService>();
builder.Services.AddScoped<RefreshCoordinator>();
builder.Services.AddTransient<JwtDelegatingHandler>();
builder.Services.AddHttpClient("Refresh", client => client.BaseAddress = apiBase);
builder.Services.AddHttpClient<BackendApi>(client => client.BaseAddress = apiBase).AddHttpMessageHandler<JwtDelegatingHandler>();
builder.Services.AddHttpClient("AuthenticatedApi", client => client.BaseAddress = apiBase).AddHttpMessageHandler<JwtDelegatingHandler>();
builder.Services.AddScoped<InvoiceService>();
builder.Services.AddScoped<CustomerService>();
builder.Services.AddScoped<ProductService>();
builder.Services.AddScoped<MoadianSettingsService>();
builder.Services.AddScoped<AdministrationService>();
builder.Services.AddScoped<ReportService>();
builder.Services.AddScoped<DashboardViewModel>();
builder.Services.AddScoped<InvoiceFormViewModel>();
builder.Services.AddScoped<InvoiceListViewModel>();
builder.Services.AddScoped<MasterDataViewModel>();
builder.Services.AddScoped<MoadianSettingsViewModel>();
builder.Services.AddScoped<AdministrationViewModel>();
builder.Services.AddScoped<ReportViewModel>();
await builder.Build().RunAsync();
